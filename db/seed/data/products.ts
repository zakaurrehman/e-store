/**
 * Zendropship launch catalogue — original product copy for house-label products.
 * `photos` are Unsplash photo ids (Unsplash License). The first photo is the main image; when only one
 * photo is listed the seed adds a close-up crop of it as the second gallery image.
 */

export type SeedOption = {
  attribute: "size" | "shoe-size" | "kids-size" | "ring-size" | "case-size" | "volume";
  values: Array<string | { value: string; price?: number; sale?: number; stock?: number }>;
};

export type SeedProduct = {
  name: string;
  brand: string;
  categories: string[];
  price: number;
  sale?: number;
  short: string;
  description: string;
  specs: Array<[string, string]>;
  care?: string;
  photos: string[];
  /** Skip the generated close-up crop (e.g. when it would expose a third-party label). */
  noDetail?: boolean;
  alt: string;
  option?: SeedOption;
  stock?: number;
  colours?: string[];
  materials?: string[];
  tags?: string[];
  featured?: boolean;
  gift?: boolean;
  daysAgo: number;
  weight?: number;
};

const APPAREL = ["XS", "S", "M", "L", "XL"];
const size = (stock: number[] = [6, 14, 18, 12, 5]): SeedOption => ({
  attribute: "size",
  values: APPAREL.map((value, index) => ({ value, stock: stock[index] ?? 8 })),
});
const shoes = (from: number, to: number, stock = 6): SeedOption => ({
  attribute: "shoe-size",
  values: Array.from({ length: to - from + 1 }, (_, index) => ({ value: String(from + index), stock: stock + ((index * 3) % 5) })),
});

